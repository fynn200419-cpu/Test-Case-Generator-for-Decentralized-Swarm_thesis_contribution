"""
Utilities for loading and processing trajectory data from MATLAB simulations.

This module provides functions to load position and velocity trajectory data
from MATLAB .mat files generated by the UAV swarm simulator, for use in
coordination-based seeding.
"""

import numpy as np
from scipy.io import loadmat
from pathlib import Path


def load_trajectory_data(mat_file_path):
    """
    Load position and velocity trajectories from MATLAB output file.

    Supports two formats:
    1. state_var.mat format: Contains pos_ned_history, vel_ned_history, time_history directly
    2. output.mat format: Contains 'out' structure with nested cell arrays

    Parameters
    ----------
    mat_file_path : str or Path
        Path to .mat file containing simulation output (e.g., state_var.mat or output.mat)

    Returns
    -------
    dict
        Dictionary with keys:
            - 'pos_ned': list of arrays, each shape (num_timesteps, 3*num_agents)
                        Format: [x1, y1, z1, x2, y2, z2, ..., xN, yN, zN]
            - 'vel_ned': list of arrays, same structure as pos_ned
            - 'time': list of 1D arrays with timestamps for each run
            - 'fail_config': list of dicts with failure configurations (may be None)
            - 'num_runs': int, number of simulation runs in the file

    Raises
    ------
    FileNotFoundError
        If the specified .mat file does not exist
    KeyError
        If the .mat file doesn't contain expected data structure
    ValueError
        If the data structure is unexpected or malformed

    Example
    -------
    >>> traj_data = load_trajectory_data('results/iter001/state_var.mat')
    >>> pos_first_run = traj_data['pos_ned'][0]  # Shape: (timesteps, 3*num_agents)
    >>> time_first_run = traj_data['time'][0]    # Shape: (timesteps,)
    """
    mat_file_path = Path(mat_file_path)

    if not mat_file_path.exists():
        raise FileNotFoundError(f"MATLAB output file not found: {mat_file_path}")

    # Load the .mat file
    mat_data = loadmat(str(mat_file_path), squeeze_me=False, struct_as_record=False)

    # Try state_var.mat format first (has pos_ned_history, vel_ned_history, time_history)
    if 'pos_ned_history' in mat_data:
        return _load_state_var_format(mat_data)

    # Fall back to output.mat format (has 'out' structure)
    if 'out' in mat_data:
        return _load_output_format(mat_data, mat_file_path)

    raise KeyError(f"Unrecognized .mat file format in {mat_file_path}. "
                   f"Expected 'pos_ned_history' or 'out' structure. "
                   f"Found keys: {[k for k in mat_data.keys() if not k.startswith('__')]}")


def _load_state_var_format(mat_data):
    """
    Load trajectory data from state_var.mat format.

    This format has direct arrays:
    - pos_ned_history: shape (num_timesteps, 3*num_agents)
    - vel_ned_history: shape (num_timesteps, 3*num_agents)
    - time_history: shape (1, num_timesteps) or (num_timesteps,)
    """
    pos_ned = mat_data['pos_ned_history']
    vel_ned = mat_data.get('vel_ned_history', None)
    time_data = mat_data['time_history']

    # Flatten time array if needed
    time_array = time_data.flatten()

    # state_var.mat contains a single run
    return {
        'pos_ned': [pos_ned],
        'vel_ned': [vel_ned] if vel_ned is not None else [None],
        'time': [time_array],
        'fail_config': [None],
        'num_runs': 1
    }


def _load_output_format(mat_data, mat_file_path):
    """
    Load trajectory data from output.mat format (legacy format with 'out' structure).
    """
    out = mat_data['out']

    # Extract data from MATLAB structure
    # MATLAB cell arrays are loaded as object arrays
    try:
        # Access fields from the MATLAB struct
        pos_ned_cell = out[0, 0].pos_ned
        vel_ned_cell = out[0, 0].vel_ned if hasattr(out[0, 0], 'vel_ned') else None
        time_cell = out[0, 0].time
        fail_config_cell = out[0, 0].fail_config if hasattr(out[0, 0], 'fail_config') else None

        # Convert MATLAB cell arrays to Python lists
        num_runs = pos_ned_cell.shape[0]

        pos_ned_list = []
        vel_ned_list = []
        time_list = []
        fail_config_list = []

        for i in range(num_runs):
            # Extract position data (handle both cell and direct array)
            pos_data = pos_ned_cell[i, 0]
            if isinstance(pos_data, np.ndarray):
                pos_ned_list.append(pos_data)
            else:
                raise ValueError(f"Unexpected pos_ned data type at index {i}")

            # Extract velocity data if available
            if vel_ned_cell is not None:
                vel_data = vel_ned_cell[i, 0]
                if isinstance(vel_data, np.ndarray):
                    vel_ned_list.append(vel_data)
                else:
                    vel_ned_list.append(None)
            else:
                vel_ned_list.append(None)

            # Extract time data
            time_data = time_cell[i, 0]
            if isinstance(time_data, np.ndarray):
                time_list.append(time_data.flatten())
            else:
                raise ValueError(f"Unexpected time data type at index {i}")

            # Extract failure config if available
            if fail_config_cell is not None:
                fail_config_struct = fail_config_cell[i, 0]
                fail_config_dict = _matlab_struct_to_dict(fail_config_struct)
                fail_config_list.append(fail_config_dict)
            else:
                fail_config_list.append(None)

        return {
            'pos_ned': pos_ned_list,
            'vel_ned': vel_ned_list,
            'time': time_list,
            'fail_config': fail_config_list,
            'num_runs': num_runs
        }

    except AttributeError as e:
        raise ValueError(f"Unexpected data structure in .mat file {mat_file_path}: {e}")


def _matlab_struct_to_dict(matlab_struct):
    """
    Convert MATLAB struct to Python dictionary.

    Parameters
    ----------
    matlab_struct : matlab.mlarray or similar
        MATLAB structure loaded by scipy.io.loadmat

    Returns
    -------
    dict
        Dictionary with field names as keys
    """
    if matlab_struct is None:
        return {}

    result = {}
    try:
        # Get all field names from the MATLAB struct
        field_names = matlab_struct._fieldnames
        for field_name in field_names:
            field_value = getattr(matlab_struct, field_name)

            # Convert numpy arrays to native Python types where appropriate
            if isinstance(field_value, np.ndarray):
                if field_value.size == 1:
                    # Scalar value
                    result[field_name] = field_value.item()
                else:
                    # Keep as array
                    result[field_name] = field_value.flatten()
            else:
                result[field_name] = field_value

    except AttributeError:
        # If not a proper struct, return empty dict
        return {}

    return result


def get_num_agents_from_trajectory(pos_ned_array):
    """
    Determine the number of agents from position trajectory array shape.

    Parameters
    ----------
    pos_ned_array : ndarray
        Position trajectory array with shape (num_timesteps, 3*num_agents)

    Returns
    -------
    int
        Number of agents in the swarm

    Raises
    ------
    ValueError
        If the array dimensions are invalid (not divisible by 3)

    Example
    -------
    >>> pos_ned = np.random.rand(1000, 30)  # 10 agents, 1000 timesteps
    >>> num_agents = get_num_agents_from_trajectory(pos_ned)
    >>> print(num_agents)  # Output: 10
    """
    if pos_ned_array.ndim != 2:
        raise ValueError(f"Expected 2D array, got {pos_ned_array.ndim}D")

    num_cols = pos_ned_array.shape[1]

    if num_cols % 3 != 0:
        raise ValueError(
            f"Position array has {num_cols} columns, which is not divisible by 3. "
            f"Expected format: [x1,y1,z1,x2,y2,z2,...]"
        )

    return num_cols // 3


def extract_agent_trajectory(pos_ned_array, agent_id):
    """
    Extract position trajectory for a single agent.

    Parameters
    ----------
    pos_ned_array : ndarray
        Position trajectory array with shape (num_timesteps, 3*num_agents)
        Format: [x1, y1, z1, x2, y2, z2, ..., xN, yN, zN]
    agent_id : int
        Agent ID (1-indexed, as used in MATLAB)

    Returns
    -------
    ndarray
        Array of shape (num_timesteps, 3) containing [x, y, z] positions for the agent

    Raises
    ------
    ValueError
        If agent_id is out of valid range

    Example
    -------
    >>> pos_ned = np.random.rand(1000, 30)  # 10 agents
    >>> agent_5_trajectory = extract_agent_trajectory(pos_ned, agent_id=5)
    >>> print(agent_5_trajectory.shape)  # Output: (1000, 3)
    """
    num_agents = get_num_agents_from_trajectory(pos_ned_array)

    if agent_id < 1 or agent_id > num_agents:
        raise ValueError(
            f"agent_id must be between 1 and {num_agents}, got {agent_id}"
        )

    # Convert to 0-indexed
    agent_idx = agent_id - 1

    # Extract the three columns for this agent
    col_indices = [3 * agent_idx, 3 * agent_idx + 1, 3 * agent_idx + 2]

    return pos_ned_array[:, col_indices]


def validate_trajectory_data(traj_data):
    """
    Validate that trajectory data has the expected structure and consistency.

    Parameters
    ----------
    traj_data : dict
        Dictionary returned by load_trajectory_data()

    Returns
    -------
    bool
        True if data is valid

    Raises
    ------
    ValueError
        If validation fails, with descriptive error message
    """
    required_keys = ['pos_ned', 'time', 'num_runs']
    for key in required_keys:
        if key not in traj_data:
            raise ValueError(f"Missing required key: {key}")

    num_runs = traj_data['num_runs']

    if len(traj_data['pos_ned']) != num_runs:
        raise ValueError(
            f"pos_ned list length ({len(traj_data['pos_ned'])}) "
            f"doesn't match num_runs ({num_runs})"
        )

    if len(traj_data['time']) != num_runs:
        raise ValueError(
            f"time list length ({len(traj_data['time'])}) "
            f"doesn't match num_runs ({num_runs})"
        )

    # Check each run has consistent dimensions
    for i in range(num_runs):
        pos_ned = traj_data['pos_ned'][i]
        time = traj_data['time'][i]

        if pos_ned is None:
            raise ValueError(f"Run {i}: pos_ned is None")

        if time is None:
            raise ValueError(f"Run {i}: time is None")

        if pos_ned.shape[0] != time.shape[0]:
            raise ValueError(
                f"Run {i}: timestep mismatch - pos_ned has {pos_ned.shape[0]} rows "
                f"but time has {time.shape[0]} elements"
            )

        # Validate position array structure
        get_num_agents_from_trajectory(pos_ned)  # Will raise if invalid

    return True