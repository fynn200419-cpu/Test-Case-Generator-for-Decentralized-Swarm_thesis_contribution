def load_pickled_trial_results(results_path, keyword):
    """
    Loads pickled results from a directory or a single .pkl file, filtering by keyword.
    """
    res_combined = []
    results_path = Path(results_path)
    if not results_path.exists():
        raise FileNotFoundError(f"Directory not found: {results_path}")

    if results_path.is_file():
        if results_path.suffix == '.pkl' and (keyword in results_path.name or keyword == ''):
            with open(results_path, 'rb') as f:
                res_combined.append(pickle.load(f))
        return res_combined

    pkl_files = sorted(results_path.glob(f"*{keyword}*.pkl"))
    for pkl_file in pkl_files:
        with open(pkl_file, 'rb') as f:
            res_combined.append(pickle.load(f))
    return res_combined
# --- End of load_pickled_trial_results ---


def verify_seeding(seeded_run_result_path, prev_run_seed_path, n_seed_param_used_in_sampler=10):
    """
    Verifies if the initial population of a seeded GA run correctly incorporates
    the best solutions from a previous run's seed data.

    Args:
        seeded_run_result_path (Path): Path to the .pkl result file of the GA run that used seeding.
        prev_run_seed_path (Path): Path to the .pkl seed file generated by the previous run.
        n_seed_param_used_in_sampler (int): The 'n_seed' parameter passed to build_seeded_sampler.
                                             Defaults to 10 as per your `run_ga_failure_modes.py`.

    Returns:
        tuple: (bool, dict) - True if seeding appears successful, False otherwise,
               and a dictionary containing comparison details.
    """
    comparison_details = {
        "seeded_run_result_path": str(seeded_run_result_path),
        "prev_run_seed_path": str(prev_run_seed_path),
        "n_seed_param_used_in_sampler": n_seed_param_used_in_sampler,
        "status": "Failed",
        "message": ""
    }

    try:
        # 1. Load the result of the seeded run
        seeded_run_data_list = load_pickled_trial_results(seeded_run_result_path, "")
        if not seeded_run_data_list:
            comparison_details["message"] = "Could not load seeded run result."
            return False, comparison_details
        current_result_dict = seeded_run_data_list[0] # Assuming it's a single result file
        current_result = current_result_dict['result']

        # # --- New code to find and print the generation of the best fitness ---
        # convergence_history = current_result_dict.get('convergence_history', [])
        # if convergence_history:
        #     convergence_history = np.array(convergence_history)
        #     sorted_indices = np.argsort(convergence_history)
        #     num_to_print = len(convergence_history)
        #     print(f"--- Top {num_to_print} Best Fitness Values from History ---")
        #     for i in range(num_to_print):
        #         idx = sorted_indices[i]
        #         print(f"  Rank {i+1}: Fitness {convergence_history[idx]:.4f} at generation {idx}")
        # # --- End of new code ---

        current_pop_size = current_result_dict['population_size'] # Get pop_size from saved result

        # 2. Get the initial population (X values) of the seeded run
        if current_result.history is None or len(current_result.history) == 0 or current_result.history[0].pop is None:
            comparison_details["message"] = "Seeded run history or initial population not found."
            return False, comparison_details
        initial_pop_X = current_result.history[0].pop.get("X")

        if initial_pop_X is None or initial_pop_X.size == 0:
            comparison_details["message"] = "Initial population of seeded run is empty."
            return False, comparison_details

        # 3. Load the seed data from the previous run
        prev_seed_data_list = load_pickled_trial_results(prev_run_seed_path, "")
        if not prev_seed_data_list:
            comparison_details["message"] = "Could not load previous run seed data."
            return False, comparison_details
        
        # Assuming the seed_pickle_path points to a single seed file, so prev_seed_data_list[0]
        prev_X_all = prev_seed_data_list[0]['X']
        prev_F_all = prev_seed_data_list[0]['F']

        if prev_X_all is None or prev_F_all is None or prev_X_all.size == 0 or prev_F_all.size == 0:
            comparison_details["message"] = "Previous run seed data (X or F) is empty."
            return False, comparison_details

        # 4. Determine the actual number of seeds that would have been used by MixedSeedSampling
        # Replicate the sorting logic from seeding.py
        # Ensure prev_F_all is a 1D array before sorting to prevent ambiguity.
        flat_F = prev_F_all.flatten()
        sorted_indices = np.argsort(flat_F)
        best_prev_solutions_X_all = prev_X_all[sorted_indices]
        best_prev_solutions_F_all = flat_F[sorted_indices]

        # --- New print statements for manual verification ---
        print("\n--- Top 10 Solutions from Previous Run (Candidates for Seeding) ---")
        num_to_print_candidates = min(10, len(best_prev_solutions_X_all))
        for i in range(num_to_print_candidates):
            print(f"  Rank {i+1}: Fitness = {best_prev_solutions_F_all[i]:.4f}, Solution (X) =", best_prev_solutions_X_all[i])
        print("--------------------------------------------------------------------")
        # --- End of new print statements ---
        
        # Simulate MixedSeedSampling's seeds_to_use calculation
        n_seed_available_from_prev_run = best_prev_solutions_X_all.shape[0]
        max_seed_pct = 0.34
        max_seeds_allowed_by_pop_size = int(np.floor(max_seed_pct * current_pop_size))
        
        # The actual number of seeds taken from the sorted previous solutions
        # is limited by n_seed_param_used_in_sampler and max_seeds_allowed_by_pop_size
        num_seeds_to_compare = min(n_seed_available_from_prev_run, n_seed_param_used_in_sampler, max_seeds_allowed_by_pop_size)

        if num_seeds_to_compare == 0:
            comparison_details["message"] = "No seeds were actually incorporated into the initial population (or none available to check)."
            comparison_details["status"] = "Successful (no seeds to verify)"
            return True, comparison_details

        expected_seeds = best_prev_solutions_X_all[:num_seeds_to_compare]
        seeds_in_initial_pop = initial_pop_X[:num_seeds_to_compare]

        # --- New print statements for manual verification ---
        print(f"\n--- Initial Population of Seeded Run (First {num_seeds_to_compare} Individuals) ---")
        if num_seeds_to_compare > 0:
            print(seeds_in_initial_pop)
        else:
            print(" (No seeds were expected to be used.)")
        print("------------------------------------------------------------------")
        # --- End of new print statements ---

        # --- New: Display fitness of seeded solutions in the new configuration ---
        print(f"\n--- Fitness of Seeded Solutions in New Configuration ({num_seeds_to_compare} Individuals) ---")
        if num_seeds_to_compare > 0:
            # Get the fitness values of the initial population
            initial_pop_F = current_result.history[0].pop.get("F")
            if initial_pop_F is not None:
                seeded_solutions_fitness_new_config = initial_pop_F[:num_seeds_to_compare]
                for i in range(num_seeds_to_compare):
                    print(f"  Seeded Solution {i+1}: Fitness = {seeded_solutions_fitness_new_config[i][0]:.4f}, X =", expected_seeds[i])
            else:
                print("  Could not retrieve fitness for the initial population.")
        else:
            print("  (No seeds were expected to be used.)")
        print("------------------------------------------------------------------")
        # --- End of new section ---

        comparison_details["num_seeds_expected_to_be_incorporated"] = num_seeds_to_compare
        comparison_details["expected_seeds_from_prev_run"] = expected_seeds
        comparison_details["actual_seeds_in_initial_pop"] = seeds_in_initial_pop
        
        # Use np.allclose for float comparisons, with a reasonable tolerance
        if np.allclose(seeds_in_initial_pop, expected_seeds, atol=1e-6, rtol=1e-6):
            comparison_details["status"] = "Successful"
            comparison_details["message"] = f"Successfully verified {num_seeds_to_compare} seeds in the initial population."
            return True, comparison_details
        else:
            comparison_details["message"] = "Mismatch found between expected seeds and initial population."
            # Optionally, find which elements don't match for more detailed debugging
            # Perform an element-wise comparison to get a boolean mask for each element
            element_wise_comparison = np.isclose(seeds_in_initial_pop, expected_seeds, atol=1e-6, rtol=1e-6)
            # A row is mismatched if any element in that row is not close (is False)
            mismatched_rows_mask = ~np.all(element_wise_comparison, axis=1)
            comparison_details["mismatched_elements_mask"] = mismatched_rows_mask
            
            # Find the index of the first mismatch to report it
            first_mismatch_idx = np.where(mismatched_rows_mask)[0][0] if np.any(mismatched_rows_mask) else None
            comparison_details["first_mismatch_details"] = {
                "expected": expected_seeds[first_mismatch_idx] if first_mismatch_idx is not None else None,
                "actual": seeds_in_initial_pop[first_mismatch_idx] if first_mismatch_idx is not None else None
            }
            return False, comparison_details

    except Exception as e:
        comparison_details["message"] = f"An error occurred during verification: {e}"
        return False, comparison_details

